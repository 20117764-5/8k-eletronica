-- Execute uma vez no SQL Editor do Supabase.
-- Cria os comprovantes de pagamento do serviço de busca/coleta de aparelhos.
begin;

create table if not exists public.saidas_busca (
  id bigint generated by default as identity primary key,
  os_id bigint not null references public.ordens_servico(id) on delete restrict,
  valor_cobrado numeric(12, 2) not null check (valor_cobrado > 0),
  data_busca date not null default current_date,
  cliente_nome text not null,
  cliente_documento text,
  cliente_telefone text,
  cliente_endereco text,
  aparelho_tipo text not null,
  marca text not null,
  modelo text,
  serial_imei text,
  created_at timestamptz not null default now()
);

create index if not exists saidas_busca_os_id_idx on public.saidas_busca (os_id);
create index if not exists saidas_busca_data_busca_idx on public.saidas_busca (data_busca desc);

alter table public.saidas_busca enable row level security;

grant select, insert, update, delete on public.saidas_busca to authenticated;
grant usage, select on sequence public.saidas_busca_id_seq to authenticated;

drop policy if exists saidas_busca_select on public.saidas_busca;
create policy saidas_busca_select on public.saidas_busca
  for select to authenticated using (true);

drop policy if exists saidas_busca_insert on public.saidas_busca;
create policy saidas_busca_insert on public.saidas_busca
  for insert to authenticated with check (true);

drop policy if exists saidas_busca_update on public.saidas_busca;
create policy saidas_busca_update on public.saidas_busca
  for update to authenticated using (true) with check (true);

drop policy if exists saidas_busca_delete on public.saidas_busca;
create policy saidas_busca_delete on public.saidas_busca
  for delete to authenticated using (true);

notify pgrst, 'reload schema';
commit;
